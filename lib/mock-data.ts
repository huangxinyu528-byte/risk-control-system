export function buildCustomerRecord(
  payload: CustomerPayload,
  existing?: CustomerRecord,
): CustomerRecord {
  const now = new Date().toISOString();
  return {
    ...payload,
    id: existing?.id ?? `cus-dev-${Date.now()}`,
    createdAt: existing?.createdAt ?? now,
    updatedAt: now,
    creditStatus: payload.creditStatus ?? existing?.creditStatus ?? "",
    currentStatus: payload.currentStatus ?? existing?.currentStatus ?? "",
  };
}

export function buildReceivableRecord(
  payload: ReceivablePayload,
  customerName: string,
  existing?: ReceivableRecord,
): ReceivableRecord {
  const amount = Number(payload.amount) || 0;
  const receivedAmount = Number(payload.receivedAmount) || 0;
  const unpaidAmount = Math.max(amount - receivedAmount, 0);
  const paymentRate = amount > 0 ? receivedAmount / amount : 0;
  const now = new Date().toISOString();

  return {
    ...payload,
    id: existing?.id ?? `recv-dev-${Date.now()}`,
    receivableNo: existing?.receivableNo ?? `AR-${Date.now()}`,
    createdAt: existing?.createdAt ?? now,
    updatedAt: now,
    customerName,
    contractReceivable: Number(payload.contractReceivable) || amount,
    cumulativeReceivable: Number(payload.cumulativeReceivable) || amount,
    statementDate: payload.statementDate ?? null,
    businessType: payload.businessType ?? "",
    timeNode: payload.timeNode ?? "",
    remark: payload.remark ?? "",
    period: payload.period,
    paymentTerm: payload.paymentTerm ?? null,
    baseDate: payload.baseDate ?? null,
    amount,
    receivedAmount,
    unpaidAmount,
    paymentRate,
    billingPeriodDays: payload.billingPeriodDays ?? null,
    dueDate: payload.dueDate ?? null,
    receivedDate: payload.receivedDate ?? null,
    isSettled: receivedAmount >= amount && amount > 0,
    overdueDays: payload.overdueDays ?? null,
    agingBucket: payload.agingBucket ?? null,
    monthlyReceivedAmount: Number(payload.monthlyReceivedAmount) || 0,
  };
}

export function buildDashboardOverviewData(
  customers: CustomerRecord[],
  receivables: ReceivableRecord[],
): DashboardOverviewData {
  const totalAmount = receivables.reduce((sum, item) => sum + item.amount, 0);
  const totalReceived = receivables.reduce((sum, item) => sum + item.receivedAmount, 0);
  const totalUnpaid = receivables.reduce((sum, item) => sum + item.unpaidAmount, 0);
  const highRiskCustomers = new Set(
    receivables.filter((item) => item.riskStatus === "高风险").map((item) => item.customerId),
  ).size;
  const litigationCustomers = new Set(
    developmentRiskRecords
      .filter((item) => item.riskType.includes("诉讼"))
      .map((item) => item.customerId),
  ).size;

  const gradeMap = customers.reduce<Record<string, number>>((acc, customer) => {
    acc[customer.currentCreditLevel] = (acc[customer.currentCreditLevel] ?? 0) + 1;
    return acc;
  }, {});

  const topCustomers = [...receivables]
    .sort((a, b) => b.unpaidAmount - a.unpaidAmount)
    .slice(0, 5)
    .map((item) => ({
      customerName: item.customerName,
      unpaidAmount: item.unpaidAmount,
      overdueDays: item.overdueDays,
      riskStatus: item.riskStatus,
    }));

  return {
    stats: [
      { label: "应收账款总额", value: formatCurrency(totalAmount), helper: "含全部在途项目" },
      { label: "已收金额", value: formatCurrency(totalReceived), helper: "累计已回款" },
      { label: "未收金额", value: formatCurrency(totalUnpaid), helper: "待继续跟进" },
      { label: "高风险客户数", value: `${highRiskCustomers}`, helper: "按风险状态识别" },
      { label: "诉讼客户数", value: `${litigationCustomers}`, helper: "含诉讼相关风险记录" },
    ],
    gradeDistribution: Object.entries(gradeMap).map(([level, count]) => ({ level, count })),
    collectionTopCustomers: topCustomers,
    riskTrend: developmentCustomerTrend,
    ruleSummary: [
      { name: "未收金额计算", status: "已启用", description: "按应收金额减已收金额计算。" },
      { name: "逾期预警", status: "未启用", description: "账期或到期日缺失时暂不自动触发。" },
    ],
    focusSummary: {
      highRiskCustomers,
      keyAttentionCustomers: customers.filter((item) => ["C", "D"].includes(item.currentCreditLevel)).length,
      creditLimitWarnings: 0,
      creditLimitRisks: 0,
      cLevelCustomers: customers.filter((item) => item.creditLevel === "C").length,
      collectionCustomers: customers.filter((item) => item.riskAction === "催款").length,
      scoreDownCustomers: customers.filter((item) => (item.scoreDelta ?? 0) < 0).length,
      litigationCustomers,
    },
  };
}

export function formatCurrency(value: number) {
  return new Intl.NumberFormat("zh-CN", {
    style: "currency",
    currency: "CNY",
    maximumFractionDigits: 0,
  }).format(value);
}

